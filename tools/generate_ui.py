#!/usr/bin/env python3
"""
generate_ui.py - Erzeugt ESPHome LVGL-Seiten und Entity-Synchronisation aus layout.json

Ablauf:
    python tools/generate_ui.py

Erzeugt (Ueberschreibt bestehende Dateien!):
    pages/<id>_page.yaml              LVGL-Seiten inkl. Swipe-Navigation
    entities/generated_entities.yaml  HA-Sensoren + Widget-Sync (on_value/on_state)
    entities/generated_navigation.yaml  change_page-Script mit Seitennamen

Danach validieren/kompilieren mit:
    esphome config main.yaml

Widget-Templates liegen in widgets/*.tpl (string.Template, ${platzhalter}).
Nur Standardbibliothek noetig.
"""

import json
import sys
from pathlib import Path
from string import Template

ROOT = Path(__file__).resolve().parent.parent
LAYOUT_FILE = ROOT / "layout.json"
TPL_DIR = ROOT / "widgets"
PAGES_DIR = ROOT / "pages"
ENTITIES_DIR = ROOT / "entities"

GENERATED_HEADER = (
    "# AUTO-GENERATED by tools/generate_ui.py - NICHT manuell editieren!\n"
    "# Quelle: layout.json | Aenderungen dort vornehmen und Generator erneut laufen lassen.\n\n"
)

# Frosted-Glass Design-Konventionen (siehe entities/global_vars.yaml)
CONTENT_DEFAULT = {"x": 30, "y": 70, "width": 740}   # Bereich zwischen Header und Footer
GRID_DEFAULT = {"columns": 2, "row_height": 64, "gap": 8}

# Domain -> Standard-Widget-Typ (wenn im Layout kein "type" angegeben ist)
DOMAIN_WIDGET = {
    "light": "light",
    "switch": "toggle",
    "input_boolean": "toggle",
    "cover": "cover",
    "sensor": "sensor-value",
    "climate": "sensor-value",
    "scene": "button",
    "script": "button",
}


def load_tpl(name):
    return Template((TPL_DIR / name).read_text(encoding="utf-8"))


def cell_rect(grid, spec, content):
    """Grid-Spezifikation [col, row, colspan?, rowspan?] -> Pixel (x, y, w, h)."""
    col, row = spec[0], spec[1]
    colspan = spec[2] if len(spec) > 2 else 1
    rowspan = spec[3] if len(spec) > 3 else 1
    cols = grid["columns"]
    gap = grid.get("gap", GRID_DEFAULT["gap"])
    row_h = grid.get("row_height", GRID_DEFAULT["row_height"])
    col_w = (content["width"] - (cols - 1) * gap) / cols
    x = round(content["x"] + col * (col_w + gap))
    w = round(colspan * col_w + (colspan - 1) * gap)
    y = content["y"] + row * (row_h + gap)
    h = rowspan * row_h + (rowspan - 1) * gap
    return x, y, w, h


# ---------------------------------------------------------------------------
# Widget-Renderer: erzeugen YAML-Fragmente, melden Slider-Zonen + Entitaeten
# ---------------------------------------------------------------------------

def render_light(w, page, rect, zones, entities):
    x, y, wd, ht = rect
    # Swipe-Aussparungen fuer die Slider der Detail-Ebene (Panel fix bei x100/y110)
    zones.append((110, 194, 690, 230))   # Helligkeits-Slider
    zones.append((110, 270, 690, 306))   # Farbtemperatur-Slider
    entities.append(("light", w, page))
    return load_tpl("light_card.tpl").substitute(
        page=page, key=w["key"], name=w["name"], entity=w["entity"],
        x=x, y=y, w=wd, h=ht,
    )


def render_light_detail(w, page):
    """Detail-Overlay: wird erst NACH allen Karten erzeugt (Z-Order ganz oben)."""
    return load_tpl("light_detail.tpl").substitute(
        page=page, key=w["key"], name=w["name"], entity=w["entity"],
    )


def render_toggle(w, page, rect, zones, entities):
    x, y, wd, ht = rect
    domain = w["entity"].split(".")[0]
    entities.append(("toggle", w, page))
    return load_tpl("toggle_card.tpl").substitute(
        page=page, key=w["key"], name=w["name"], entity=w["entity"], domain=domain,
        x=x, y=y, w=wd, h=ht,
        label_x=x + 14, label_y=y + 20,
        switch_x=x + wd - 62, switch_y=y + 20,
    )


def render_sensor_value(w, page, rect, zones, entities):
    x, y, wd, ht = rect
    entities.append(("sensor-value", w, page))
    return load_tpl("sensor_value.tpl").substitute(
        page=page, key=w["key"], name=w["name"], entity=w["entity"],
        x=x, y=y, w=wd, h=ht,
        label_x=x + 12, label_y=y + 6,
        value_y=y + 30,
    )


def render_clock(w, page, rect, zones, entities):
    x, y, wd, ht = rect
    return load_tpl("clock.tpl").substitute(
        page=page, key=w["key"], x=x, y=y, w=wd, h=ht,
    )


def render_cover(w, page, rect, zones, entities):
    x, y, wd, ht = rect
    btn_w = (wd - 40) // 3
    entities.append(("cover", w, page))
    return load_tpl("cover_card.tpl").substitute(
        page=page, key=w["key"], name=w["name"], entity=w["entity"],
        x=x, y=y, w=wd, h=ht,
        label_x=x + 12, label_y=y + 6,
        pos_x=x + wd - 82,
        btn_x=x + 10, stop_x=x + 20 + btn_w, down_x=x + 30 + 2 * btn_w,
        btn_y=y + ht - 32, btn_w=btn_w,
    )


def render_thermostat(w, page, rect, zones, entities):
    x, y, wd, ht = rect
    size = min(wd, ht) - 32
    arc_x = x + (wd - size) // 2
    arc_y = y + (ht - size) // 2
    cy = arc_y + size // 2  # vertikale Mitte des Arc
    entities.append(("thermostat", w, page))
    return load_tpl("thermostat.tpl").substitute(
        page=page, key=w["key"], entity=w["entity"],
        min=w.get("min", 10), max=w.get("max", 30),
        arc_x=arc_x, arc_y=arc_y, arc_size=size,
        caption_y=cy - 70,
        current_y=cy - 40,
        target_y=cy + 34,
    )


def render_backlight_slider(w, page, rect, zones, entities):
    x, y, wd, ht = rect
    slider_x, slider_y = x + 300, y + 10
    slider_w = wd - 320
    zones.append((slider_x - 10, slider_y - 8, slider_x + slider_w + 10, slider_y + 26))
    return load_tpl("backlight_slider.tpl").substitute(
        page=page, key=w["key"], name=w["name"],
        x=x, y=y, w=wd, h=ht,
        label_x=x + 20, label_y=y + 8,
        slider_x=slider_x, slider_y=slider_y, slider_w=slider_w,
    )


def render_number_slider(w, page, rect, zones, entities):
    x, y, wd, ht = rect
    slider_x, slider_y = x + 300, y + 10
    slider_w = wd - 320
    zones.append((slider_x - 10, slider_y - 8, slider_x + slider_w + 10, slider_y + 26))
    return load_tpl("number_slider.tpl").substitute(
        page=page, key=w["key"], name=w["name"],
        bind=w["bind"], unit=w.get("unit", ""),
        min=w.get("min", 0), max=w.get("max", 100),
        x=x, y=y, w=wd, h=ht,
        label_x=x + 20, label_y=y + 8,
        slider_x=slider_x, slider_y=slider_y, slider_w=slider_w,
        value_y=y + 38,
    )


def render_button(w, page, rect, zones, entities):
    x, y, wd, ht = rect
    service = w.get("service", f'{w["entity"].split(".")[0]}.turn_on')
    data = w.get("service_data", {"entity_id": w.get("entity", "")})
    if data:
        lines = "\n".join(f"              {k}: {v}" for k, v in data.items())
        data_block = "            data:\n" + lines
    else:
        data_block = ""
    return load_tpl("button_card.tpl").substitute(
        page=page, key=w["key"], name=w["name"], service=service,
        service_data_block=data_block,
        x=x, y=y, w=wd, h=ht,
    )


RENDERERS = {
    "light": render_light,
    "toggle": render_toggle,
    "sensor-value": render_sensor_value,
    "clock": render_clock,
    "thermostat": render_thermostat,
    "cover": render_cover,
    "backlight-slider": render_backlight_slider,
    "number-slider": render_number_slider,
    "button": render_button,
}


# ---------------------------------------------------------------------------
# Seiten-Assembly (inkl. Swipe-Navigation via change_page-Script)
# ---------------------------------------------------------------------------

def gesture_lambda(direction, zones):
    """Lambda, das die Swipe-Richtung prueft und Slider-Bereiche ausnimmt."""
    lines = [
        "lv_indev_t *indev = lv_indev_get_act();",
        f"if (indev == nullptr || lv_indev_get_gesture_dir(indev) != LV_DIR_{direction}) return false;",
    ]
    if zones:
        lines += [
            "// Slider-Bereiche von der Swipe-Navigation ausnehmen",
            "lv_point_t point;",
            "lv_indev_get_point(indev, &point);",
        ]
        for x0, y0, x1, y1 in zones:
            lines.append(
                f"if (point.y >= {max(y0, 0)} && point.y <= {y1} "
                f"&& point.x >= {max(x0, 0)} && point.x <= {x1}) return false;"
            )
    lines.append("return true;")
    return lines


def build_page(page_cfg, content):
    page_id = page_cfg["id"]
    grid = dict(GRID_DEFAULT)
    grid.update(page_cfg.get("grid", {}))

    fragments = [load_tpl("background.tpl").substitute()]
    overlays = []  # Popups zuletzt erzeugen, damit sie ueber allen Karten liegen
    zones = []
    entities = []
    for w in page_cfg.get("widgets", []):
        wtype = w.get("type") or DOMAIN_WIDGET[w["entity"].split(".")[0]]
        if wtype not in RENDERERS:
            sys.exit(f"FEHLER: Unbekannter Widget-Typ '{wtype}' (Seite {page_id})")
        rect = cell_rect(grid, w["grid"], content)
        fragments.append(RENDERERS[wtype](w, page_id, rect, zones, entities))
        if wtype == "light":
            overlays.append(render_light_detail(w, page_id))
    fragments.extend(overlays)

    lines = [
        f"id: {page_id}_page",
        "scrollable: false",
        "on_gesture:",
    ]
    for direction, script_dir, lvgl_action in (
        ("LEFT", 1, "lvgl.page.next"),
        ("RIGHT", -1, "lvgl.page.previous"),
    ):
        lines += [
            "  - if:",
            "      condition:",
            "        lambda: |-",
        ]
        lines += [f"          {l}" for l in gesture_lambda(direction, zones)]
        lines += [
            "      then:",
            "        - script.execute:",
            "            id: change_page",
            f"            direction: {script_dir}",
            f"        - {lvgl_action}:",
        ]
    lines.append("widgets:")
    for frag in fragments:
        lines += ["  " + l if l.strip() else l for l in frag.splitlines()]
    return "\n".join(lines) + "\n", entities


# ---------------------------------------------------------------------------
# Entity-Generierung (HA-Sensoren mit Widget-Synchronisation)
# ---------------------------------------------------------------------------

def entity_blocks(kind, w, page):
    """Gibt (section, yaml_block) Tupel-Liste fuer ein Widget zurueck."""
    key, entity = w["key"], w["entity"]
    domain = entity.split(".")[0]
    blocks = []

    if kind in ("light", "toggle"):
        toggle_id = f"{page}_page_{key}_toggle"
        blocks.append(("binary_sensor", f"""  - platform: homeassistant
    entity_id: {entity}
    id: {domain}_{key}_state
    internal: true
    on_state:
      then:
        - lambda: |-
            if (id({toggle_id}) != nullptr) {{
              bool checked = lv_obj_has_state(id({toggle_id}), LV_STATE_CHECKED);
              if (checked != (bool)x) {{
                if (x) {{ lv_obj_add_state(id({toggle_id}), LV_STATE_CHECKED); }}
                else   {{ lv_obj_clear_state(id({toggle_id}), LV_STATE_CHECKED); }}
              }}
            }}"""))

    if kind == "light":
        slider_id = f"{page}_page_{key}_brightness"
        blocks.append(("sensor", f"""  - platform: homeassistant
    entity_id: {entity}
    id: {domain}_{key}_brightness
    attribute: brightness
    internal: true
    on_value:
      then:
        - lambda: |-
            if (!isnan(x) && id({slider_id}) != nullptr) {{
              int v = (int)x;
              if (lv_slider_get_value(id({slider_id})) != v) {{
                lv_slider_set_value(id({slider_id}), v, LV_ANIM_OFF);
              }}
            }}"""))

    if kind == "light":
        ct_slider_id = f"{page}_page_{key}_color_temp"
        blocks.append(("sensor", f"""  - platform: homeassistant
    entity_id: {entity}
    id: {domain}_{key}_color_temp
    attribute: color_temp_kelvin
    internal: true
    on_value:
      then:
        - lambda: |-
            if (!isnan(x) && id({ct_slider_id}) != nullptr) {{
              int v = (int)x;
              if (lv_slider_get_value(id({ct_slider_id})) != v) {{
                lv_slider_set_value(id({ct_slider_id}), v, LV_ANIM_OFF);
              }}
            }}"""))

    if kind == "cover":
        pos_label = f"{page}_page_{key}_position_value"
        blocks.append(("sensor", f"""  - platform: homeassistant
    entity_id: {entity}
    id: {key}_position
    attribute: current_position
    internal: true
    on_value:
      then:
        - lambda: |-
            if (id({pos_label}) != nullptr) {{
              if (isnan(x)) {{ lv_label_set_text(id({pos_label}), "-- %"); }}
              else {{ lv_label_set_text_fmt(id({pos_label}), "%.0f %%", x); }}
            }}"""))

    if kind == "thermostat":
        arc_id = f"{page}_page_{key}_arc"
        cur_label = f"{page}_page_{key}_current_value"
        tgt_label = f"{page}_page_{key}_target_value"
        # Ist-Temperatur -> grosser Wert in der Arc-Mitte
        blocks.append(("sensor", f"""  - platform: homeassistant
    entity_id: {w['current_entity']}
    id: {key}_current_temp
    internal: true
    on_value:
      then:
        - lambda: |-
            if (id({cur_label}) != nullptr) {{
              lv_label_set_text_fmt(id({cur_label}), "%.1f °C", x);
            }}"""))
        # Soll-Temperatur (HA -> Arc + Label), mit Loop-Guard
        blocks.append(("sensor", f"""  - platform: homeassistant
    entity_id: {entity}
    id: {key}_target_temp
    attribute: target_temperature
    internal: true
    on_value:
      then:
        - lambda: |-
            if (!isnan(x) && id({arc_id}) != nullptr) {{
              if (lv_arc_get_value(id({arc_id})) != (int)x) {{
                lv_arc_set_value(id({arc_id}), (int)x);
              }}
              lv_label_set_text_fmt(id({tgt_label}), "Soll: %.0f °C", x);
            }}"""))

    if kind == "sensor-value":
        label_id = f"{page}_page_{key}_value"
        attr = f"\n    attribute: {w['attribute']}" if w.get("attribute") else ""
        if w.get("text"):
            blocks.append(("text_sensor", f"""  - platform: homeassistant
    entity_id: {entity}
    id: {key}
    internal: true{attr}
    on_value:
      then:
        - lambda: |-
            if (id({label_id}) != nullptr) {{
              lv_label_set_text(id({label_id}), x.c_str());
            }}"""))
        else:
            fmt = w.get("format", "%.1f")
            blocks.append(("sensor", f"""  - platform: homeassistant
    entity_id: {entity}
    id: {key}
    internal: true{attr}
    on_value:
      then:
        - lambda: |-
            if (id({label_id}) != nullptr) {{
              lv_label_set_text_fmt(id({label_id}), "{fmt}", x);
            }}"""))
    return blocks


def build_entities_file(all_entities):
    sections = {"binary_sensor": [], "sensor": [], "text_sensor": []}
    seen = set()
    for kind, w, page in all_entities:
        for section, block in entity_blocks(kind, w, page):
            entity_id = next(l.split("id: ")[1].strip() for l in block.splitlines()
                             if l.strip().startswith("id: "))
            if entity_id in seen:
                sys.exit(f"FEHLER: Doppelte Entity-ID '{entity_id}'")
            seen.add(entity_id)
            sections[section].append(block)

    out = []
    for section, blocks in sections.items():
        if blocks:
            out.append(f"{section}:\n" + "\n\n".join(blocks))
    return "\n\n".join(out) + "\n"


def build_navigation_file(titles):
    quoted = ", ".join(f'"{t}"' for t in titles)
    return f"""script:
  # Seitenwechsel: Index aktualisieren (+direction, mit Wrap-Around)
  # und Seitennamen im Footer setzen. Seitenliste kommt aus layout.json.
  - id: change_page
    parameters:
      direction: int
    then:
      - lambda: |-
          static const char* page_names[] = {{{quoted}}};
          static const int page_count = sizeof(page_names) / sizeof(page_names[0]);

          id(current_page_index) = (id(current_page_index) + direction + page_count) % page_count;
          lv_label_set_text(id(page_name_label), page_names[id(current_page_index)]);
"""


# ---------------------------------------------------------------------------

def main():
    layout = json.loads(LAYOUT_FILE.read_text(encoding="utf-8"))
    content = dict(CONTENT_DEFAULT)
    content.update(layout.get("content", {}))

    all_entities = []
    titles = []
    for page_cfg in layout["pages"]:
        page_yaml, entities = build_page(page_cfg, content)
        out = PAGES_DIR / f"{page_cfg['id']}_page.yaml"
        out.write_text(GENERATED_HEADER + page_yaml, encoding="utf-8", newline="\n")
        print(f"  erzeugt: {out.relative_to(ROOT)} ({len(page_cfg.get('widgets', []))} Widgets)")
        all_entities.extend(entities)
        titles.append(page_cfg["title"])

    (ENTITIES_DIR / "generated_entities.yaml").write_text(
        GENERATED_HEADER + build_entities_file(all_entities),
        encoding="utf-8", newline="\n")
    print(f"  erzeugt: entities/generated_entities.yaml ({len(all_entities)} Widget-Entitaeten)")

    (ENTITIES_DIR / "generated_navigation.yaml").write_text(
        GENERATED_HEADER + build_navigation_file(titles),
        encoding="utf-8", newline="\n")
    print(f"  erzeugt: entities/generated_navigation.yaml (Seiten: {', '.join(titles)})")

    print("\nFertig. Validieren mit: esphome config main.yaml")


if __name__ == "__main__":
    main()
